/******************************************************************************
    Warsztaty SQL Server 2025 - Regex
    Część 4 - Listy i analiza tekstu

    Przykładowe rozwiązania
******************************************************************************/

USE AdventureWorks2025;
GO

/******************************************************************************
Zadanie 1
******************************************************************************/

SELECT *
FROM REGEXP_SPLIT_TO_TABLE('SQL,Fabric,Azure,Power BI', ',');
GO

/******************************************************************************
Zadanie 2
******************************************************************************/

SELECT *
FROM REGEXP_SPLIT_TO_TABLE('SQL;Fabric,Azure|Power BI', '[,;|]');
GO

/******************************************************************************
Zadanie 3
******************************************************************************/

SELECT
    REGEXP_COUNT('SQL,Fabric,Azure,Power BI', ',') + 1 AS ItemCount;
GO

/******************************************************************************
Zadanie 4
******************************************************************************/

SELECT *
FROM REGEXP_SPLIT_TO_TABLE('adam@firma.pl;anna@test.com;jan@contoso.com', ';');
GO

/******************************************************************************
Zadanie 5
******************************************************************************/

SELECT *
FROM REGEXP_SPLIT_TO_TABLE('HL-U509-R,LL-R230,FR-R92B', ',');
GO

/******************************************************************************
Zadanie 6
******************************************************************************/

SELECT *
FROM REGEXP_SPLIT_TO_TABLE('ERR-100,ERR-200,ERR-300', ',');
GO

/******************************************************************************
Zadanie 7
******************************************************************************/

SELECT
    value,
    REGEXP_SUBSTR(value, '\d+') AS ErrorNumber
FROM REGEXP_SPLIT_TO_TABLE('ERR-100,ERR-200,ERR-300', ',');
GO

/******************************************************************************
Zadanie 8
******************************************************************************/

SELECT
    REGEXP_REPLACE(
        value,
        '^\s+|\s+$',
        ''
    ) AS Technology
FROM REGEXP_SPLIT_TO_TABLE(
    'SQL, Fabric, Azure, Power BI',
    ','
);
GO

/******************************************************************************
Zadanie 9
******************************************************************************/

SELECT
    REGEXP_COUNT('adam@firma.pl;anna@test.com;jan@contoso.com', ';') + 1 AS EmailCount;
GO

/******************************************************************************
Zadanie 10
******************************************************************************/

SELECT
    value,
    REGEXP_SUBSTR(
        REGEXP_REPLACE(
            value,
            '^\s+|\s+$',
            ''
        ),
        '\d+'
    ) AS ErrorNumber
FROM REGEXP_SPLIT_TO_TABLE(
    'ERR-100; ERR-200; ERR-300',
    ';'
);
GO