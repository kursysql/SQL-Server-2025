/******************************************************************************
    Warsztaty SQL Server 2025 - Regex
    Część 3 - Wyodrębnianie informacji

    Przykładowe rozwiązania
******************************************************************************/

USE AdventureWorks2025;
GO

/******************************************************************************
Zadanie 1
******************************************************************************/

SELECT REGEXP_SUBSTR(
    'Faktura FV/2025/00123',
    'FV/[0-9]{4}/[0-9]+'
);
GO

/******************************************************************************
Zadanie 2
******************************************************************************/

SELECT
    EmailAddress,
    REGEXP_SUBSTR(EmailAddress, '@(.+)$', 1, 1, 'c', 1) AS Domain
FROM Person.EmailAddress;
GO

/******************************************************************************
Zadanie 3
******************************************************************************/

SELECT
    ProductNumber,
    REGEXP_SUBSTR(ProductNumber, '\d') AS FirstDigit
FROM Production.Product;
GO

/******************************************************************************
Zadanie 4
******************************************************************************/

SELECT REGEXP_SUBSTR('SQL Server 2025', '\d+');
GO

/******************************************************************************
Zadanie 5
******************************************************************************/

SELECT *
FROM REGEXP_MATCHES('Produkt A123, B456 oraz C789', '[A-Z][0-9]{3}');
GO

/******************************************************************************
Zadanie 6
******************************************************************************/

SELECT
    EmailAddress,
    REGEXP_SUBSTR(EmailAddress, '^[^@]+') AS LoginPart
FROM Person.EmailAddress;
GO

/******************************************************************************
Zadanie 7
******************************************************************************/

SELECT *
FROM REGEXP_MATCHES(
    'Kontakt: adam@firma.pl, anna@test.com',
    '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}'
);
GO

/******************************************************************************
Zadanie 8
******************************************************************************/

SELECT
    ProductNumber,
    REGEXP_SUBSTR(ProductNumber, '\d+') AS NumberPart
FROM Production.Product;
GO

/******************************************************************************
Zadanie 9
******************************************************************************/

SELECT *
FROM REGEXP_MATCHES('Błąd ERR-100, ERR-200, ERR-300', 'ERR-[0-9]+');
GO

/******************************************************************************
Zadanie 10
******************************************************************************/

SELECT REGEXP_SUBSTR('Plik backup_20250615.zip', '\d{8}');
GO